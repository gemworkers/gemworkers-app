-- =============================================================================
-- GemWorkers — Ship-to countries (tax & duties plan, step 1)
-- =============================================================================
-- Applied to live DB 2026-10-23
--
-- public.shipping_countries — the countries the store ships to. The buyer
-- picks a ship-to country before checkout; Stripe only accepts that country,
-- so later tax/duty calculation always matches the real destination.
--   code    ISO 3166-1 alpha-2 (Stripe's format)
--   enabled false = shown as "we don't ship there yet — contact us"
--   region  for grouping in the chooser and, later, for tax rules
-- Everyone may read (store chooser); only the owner edits (admin, step 2).
-- Seeded worldwide (Zakaria 2026-10-23: "everywhere Etsy ships, no legal restriction"):
-- 237 countries; switched OFF: RU, BY (EU luxury/gem export bans), IR, KP, SY,
-- CU (sanctions) and uninhabited AQ, BV, TF. Stripe-unsupported territories
-- (AS CX CC HM MH FM NF MP PW SD UM VI) are left out entirely.
-- Names: English (Intl.DisplayNames). Owner can switch countries on/off later.
-- =============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public.shipping_countries (
  code       text        PRIMARY KEY CHECK (code ~ '^[A-Z]{2}$'),
  name       text        NOT NULL,
  region     text        NOT NULL,
  enabled    boolean     NOT NULL DEFAULT true,
  sort_order integer     NOT NULL DEFAULT 100,
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.shipping_countries ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS shipping_countries_public_read ON public.shipping_countries;
DROP POLICY IF EXISTS shipping_countries_owner       ON public.shipping_countries;

CREATE POLICY shipping_countries_public_read
  ON public.shipping_countries FOR SELECT
  TO anon, authenticated
  USING (true);

CREATE POLICY shipping_countries_owner
  ON public.shipping_countries FOR ALL
  TO authenticated
  USING      (public.is_owner())
  WITH CHECK (public.is_owner());

REVOKE ALL ON public.shipping_countries FROM anon, authenticated;
GRANT SELECT ON public.shipping_countries TO anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.shipping_countries TO authenticated;

