// One-off move of stone photos/videos from Supabase Storage to Bunny
// (sql/media_bunny.sql). Run from gemworkers_store (uses its sharp):
//   node ../gemworkers_core/tools/media_migration/migrate.js <rows.jsonl> <out_dir>
// rows.jsonl: one {"id","image_urls","video_url"} per line (stones still on Supabase).
// Env GW_MIGRATE_TOKEN = Supabase secret MEDIA_MIGRATE_TOKEN (never printed).
//
// Photos: copied (full ≤ 2000 px + 800 px card), each checked on
// media.gemworkers.com; the new address list is written to <out>/switch_photos.sql,
// which only changes a stone whose photos are still exactly the old list.
// Videos: sent to Bunny Stream; the stone keeps its old video until Bunny has
// encoded the new one (webhook), then the function switches it.
// Old Supabase files are NOT deleted here (that's the clean-up, ~2 weeks later).
// Safe to re-run: photo names are fixed (m-<old name>), so a re-run overwrites.

const fs = require('fs')
const path = require('path')
const sharp = require(require.resolve('sharp', { paths: [process.cwd()] }))

const FN = 'https://cvqzidqnwthzfodhzepz.supabase.co/functions/v1/media'
const TOKEN = process.env.GW_MIGRATE_TOKEN
const [rowsFile, outDir] = process.argv.slice(2)
if (!TOKEN || !rowsFile || !outDir) { console.error('usage: GW_MIGRATE_TOKEN=… node migrate.js rows.jsonl out_dir'); process.exit(1) }
fs.mkdirSync(outDir, { recursive: true })

const rows = fs.readFileSync(rowsFile, 'utf8').trim().split('\n').filter(Boolean).map(l => JSON.parse(l))
const isOldPhoto = u => u.includes('/storage/v1/object/public/inventory-images/')
const isOldVideo = u => !!u && u.includes('/storage/v1/object/public/inventory-videos/')
const q = s => `'${String(s).replace(/'/g, "''")}'`

async function head(url) {
  const r = await fetch(url, { method: 'HEAD' })
  return r.ok ? Number(r.headers.get('content-length') || 0) : 0
}

async function movePhoto(itemId, url) {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`download ${res.status} ${url}`)
  const src = Buffer.from(await res.arrayBuffer())
  // rotate(): apply the phone's EXIF orientation before it is dropped.
  const full = await sharp(src).rotate().resize({ width: 2000, height: 2000, fit: 'inside', withoutEnlargement: true }).jpeg({ quality: 90, mozjpeg: true }).toBuffer()
  const card = await sharp(src).rotate().resize({ width: 800, withoutEnlargement: true }).jpeg({ quality: 82, mozjpeg: true }).toBuffer()
  const name = 'm-' + path.basename(new URL(url).pathname).replace(/\.[A-Za-z0-9]+$/, '').replace(/[^A-Za-z0-9._-]/g, '_')
  const form = new FormData()
  form.set('item_id', itemId)
  form.set('name', name)
  form.set('file', new Blob([full], { type: 'image/jpeg' }), 'photo.jpg')
  form.set('card', new Blob([card], { type: 'image/jpeg' }), 'card.jpg')
  const up = await fetch(FN, { method: 'POST', headers: { 'x-migrate-token': TOKEN }, body: form })
  const data = await up.json()
  if (!up.ok) throw new Error(`upload ${up.status} ${data.error}`)
  const newUrl = data.url
  const [a, b] = await Promise.all([head(newUrl), head(newUrl.replace(/\.jpg$/, '_card.jpg'))])
  if (!a || !b) throw new Error(`not found after upload: ${newUrl}`)
  return { newUrl, oldBytes: src.length, fullBytes: a, cardBytes: b }
}

;(async () => {
  const log = []
  const sql = [
    '-- GemWorkers — switch stone photos to Bunny (generated by tools/media_migration/migrate.js)',
    `-- ${new Date().toISOString()} · each UPDATE only applies if the stone still has exactly the old photo list.`,
    'BEGIN;',
  ]
  let photos = 0, videos = 0, failures = 0
  for (const r of rows) {
    const urls = r.image_urls || []
    if (urls.some(isOldPhoto)) {
      const next = []
      let ok = true
      for (const u of urls) {
        if (!isOldPhoto(u)) { next.push(u); continue }
        try {
          const m = await movePhoto(r.id, u)
          next.push(m.newUrl)
          photos++
          log.push({ id: r.id, kind: 'photo', old: u, ...m })
          process.stdout.write('.')
        } catch (e) {
          ok = false; failures++
          log.push({ id: r.id, kind: 'photo', old: u, error: String(e.message || e) })
          process.stdout.write('x')
        }
      }
      if (ok) sql.push(`UPDATE public.inventory_items SET image_urls = ${q(JSON.stringify(next))}::jsonb WHERE id = ${q(r.id)} AND image_urls = ${q(JSON.stringify(urls))}::jsonb;`)
      else sql.push(`-- ${r.id}: skipped (a photo failed, see log)`)
    }
    if (isOldVideo(r.video_url)) {
      const res = await fetch(FN, {
        method: 'POST',
        headers: { 'x-migrate-token': TOKEN, 'content-type': 'application/json' },
        body: JSON.stringify({ action: 'import_video', item_id: r.id, source_url: r.video_url }),
      })
      const data = await res.json()
      if (res.ok) { videos++; log.push({ id: r.id, kind: 'video', old: r.video_url, video_id: data.video_id }); process.stdout.write('V') }
      else { failures++; log.push({ id: r.id, kind: 'video', old: r.video_url, error: data.error }); process.stdout.write('X') }
    }
  }
  sql.push(
    '-- Check: stones that still show Supabase photos (should be 0 rows)',
    "SELECT id, title FROM public.inventory_items WHERE image_urls::text LIKE '%/inventory-images/%';",
    'COMMIT;',
  )
  fs.writeFileSync(path.join(outDir, 'switch_photos.sql'), sql.join('\n') + '\n')
  fs.writeFileSync(path.join(outDir, 'migration_log.json'), JSON.stringify(log, null, 2))
  console.log(`\nphotos ${photos}, videos ${videos}, failures ${failures}`)
})()
